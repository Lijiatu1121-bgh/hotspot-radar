# ---------- 争议类型：由问句结构推断，决定内容该怎么论证 ----------
DEBATE_PATTERNS = [
    ('因果追问', ['为什么', '为何', '原因', '怎么会', '是什么导致'], '先给机制，再给证据；忌用相关性冒充因果。'),
    ('价值判断', ['如何看待', '怎么评价', '如何评价', '应该', '该不该', '值不值', '合理吗'], '先明确评价坐标系（效率 / 公平 / 长期），否则各说各话。'),
    ('对立裁决', ['谁说得对', '谁对谁错', '哪个更', '还是', '更好'], '先拆出双方各自成立的前提，再指出前提何时失效。'),
    ('事实核验', ['是不是', '是否', '真的', '到底', '有多少', '多久', '能不能'], '先定口径再给数，口径不清时明确说「无法判断」。'),
    ('趋势预测', ['会', '未来', '接下来', '多久之后'], '给条件式预测：在什么条件下成立，触发信号是什么。'),
    ('现象解释', ['什么水平', '怎么回事', '意味着', '说明'], '先做同类对标，再判断是异常还是常态。'),
]


def _hits(text, kws):
    low = text.lower()
    return [k for k in kws if k.lower() in low]


def classify(item):
    """返回 (知识域 dict 或 None, 命中关键词列表)。

    标题命中权重 ×3、摘要命中 ×1：标题才是议题主体，
    只靠摘要容易把「一个人会做几个菜」误算进医学域（摘要里出现"营养"）。
    """
    title = item.get('title', '')
    excerpt = item.get('excerpt', '')
    best, best_hits, best_score = None, [], 0
    for d in DOMAINS:
        ht = _hits(title, d['kw'])
        he = _hits(excerpt, d['kw'])
        s = 3 * len(ht) + len(he)
        if s > best_score:
            best, best_hits, best_score = d, (ht or he), s
    return best, best_hits


def excluded(item):
    """命中排除规则返回 (类型, 命中的词)，否则 None。只看标题（见 EXCLUDE 上方说明）。"""
    text = item.get('title', '')
    for rule in EXCLUDE:
        h = _hits(text, rule['kw'])
        if h:
            return rule['kind'], h
    return None


def debate_kind(title):
    for name, kws, tip in DEBATE_PATTERNS:
        if any(k in title for k in kws):
            return name, tip
    return '泛讨论', '先补事实缺口，再下判断。'


def score(item, domain, hits):
    """四维价值分（0-100），返回明细，保证报告里每个分数都可解释。"""
    title = item.get('title', '')
    ans = item.get('answer_count') or 0
    heat = item.get('heat') or 0

    # 知识密度 0-40：命中领域关键词数 + 是否带机制类问法
    dens = min(28, 8 + 4 * len(hits))
    if any(k in title for k in ('为什么', '原理', '机制', '原因', '如何', '怎么')):
        dens += 8
    dens = min(40, dens)

    # 讨论空间 0-30：回答数分档（回答多说明能辩起来）
    if ans >= 300:
        space = 30
    elif ans >= 150:
        space = 24
    elif ans >= 80:
        space = 18
    elif ans >= 40:
        space = 12
    else:
        space = 6

    # 时效性 0-20：是否贴着当下的产业/政策/技术变化
    now_kw = ['IPO', '上市', '发布', '崩了', '故障', '涨价', '降价', '政策', '新规', '裁员',
              '会晤', '峰会', '财报', '定价', '关停', '召回', '开分', '数据']
    rec = 20 if any(k in title for k in now_kw) else (10 if heat >= 1e6 else 6)

    # 可延展 0-10：有具体主体和数字，才做得出有信息量的内容
    import re
    ext = 5
    if re.search(r'\d', title):
        ext += 3
    if len(title) >= 16:
        ext += 2
    ext = min(10, ext)

    return {
        'density': dens, 'space': space, 'recency': rec, 'extend': ext,
        'total': dens + space + rec + ext,
    }


def analyze(item):
    """完整分析一条议题，返回结构化洞察。"""
    text = f"{item.get('title','')} {item.get('excerpt','')}"
    domain, hits = classify(item)
    kind, tip = debate_kind(item.get('title', ''))
    sc = score(item, domain, hits)
    if domain is None:
        # 归不进任何知识域，通常意味着它没有可验证的知识底盘（纯观点/纯情绪），价值分下调
        sc = dict(sc)
        sc['total'] = max(0, sc['total'] - 12)
        sc['penalty'] = '未归入知识域 −12'

    out = {
        'domain': domain['name'] if domain else '未归类',
        'hits': hits,
        'frame': domain['frame'] if domain else
                 '这条议题没有命中既定知识域，需要人工判断它属于哪类问题；'
                 '若无法归入任何「有可验证事实」的领域，大概率属于情绪话题。',
        'lens': domain['lens'] if domain else ['先确认事实基础', '再确认争议点', '最后看有没有可检验的证据'],
        'ask': domain['ask'] if domain else ['这条议题的事实基础是什么？', '争论的双方各自成立的前提是什么？'],
        'debate': kind,
        'debate_tip': tip,
        'score': sc,
    }
    return out
